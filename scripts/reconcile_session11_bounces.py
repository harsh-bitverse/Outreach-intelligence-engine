    print("  SESSION 11: LIVE IMAP BOUNCE RECONCILIATION & REVERIFICATION")
    print("=" * 80)

    reconciler = BounceReconciler()
    monitor = IMAPBounceMonitor()

    # Step 1: Scan IMAP mailbox in strictly read-only mode
    print("\n[1/4] Scanning IIT Delhi IMAP mailbox (INBOX) in READ-ONLY mode...")
    dsns = reconciler.scan_imap_mailbox(folder="INBOX", since_date="01-Nov-2026")
    print(f"      Discovered {len(dsns)} campaign delivery-status notifications.")

    # Step 2: Reconcile notifications across SQLite and Excel
    print("\n[2/4] Applying reconciliation transactionally to SQLite and Excel...")
    stats = reconciler.reconcile_notifications(dsns)
    print(f"      Total notifications inspected: {stats['total_inspected']}")
    print(f"      Unique bounced recipients:     {stats['unique_dsns']}")
    print(f"      Matched professors:            {stats['matched_professors']}")
    print(f"      BOUNCED_INVALID_ADDRESS:       {stats['bounced_invalid_address']}")
    print(f"      BOUNCED_PERMANENT_OTHER:       {stats['bounced_permanent_other']}")
    print(f"      TEMPORARY_DELIVERY_FAILURE:    {stats['temporary_delivery_failure']}")
    print(f"      NEEDS_REVIEW:                  {stats['needs_review']}")
    print(f"      SQLite records updated:        {stats['sqlite_updated']}")
    print(f"      Excel rows updated:            {stats['excel_updated']}")

    # Step 3: Record researched proposed replacements in SQLite
    print("\n[3/4] Persisting 56 researched proposed replacement records in SQLite...")
    recorded_replacements = 0
    for r in REPLACEMENT_RESEARCH_DATA:
        reconciler.record_proposed_replacement(
            professor_id=r["professor_id"],
            professor_name=r["professor_name"],
            original_bounced_email=r["original_bounced_email"],
            proposed_email=r["proposed_email"],
            replacement_status=r["replacement_status"],
            current_institution=r["current_institution"],
            department=r["department"],
            source_url=r["source_url"],
            evidence_notes=r["evidence_notes"],
        )
        recorded_replacements += 1
    print(f"      Recorded {recorded_replacements} proposed replacement records.")

    # Step 4: Update checkpoint for automatic ongoing monitoring
    print("\n[4/4] Updating durable checkpoint for ongoing IMAP bounce monitoring...")
    max_uid = max([d.uid for d in dsns]) if dsns else 0
    # Save checkpoint with current folder UID
    monitor.save_checkpoint(uidvalidity=1, last_seen_uid=max_uid)
    print(f"      Checkpoint saved at last_seen_uid = {max_uid}.")

    print("\n" + "=" * 80)
    print("  RECONCILIATION COMPLETE")
    print("=" * 80)


